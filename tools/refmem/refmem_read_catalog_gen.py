#!/usr/bin/env python3
"""Generate the REFMEM read-catalog C table and header from YAML.

Mirrors tools/refmem/refmem_command_catalog_gen.py: the YAML is the single
source of truth, the generated files carry the "AUTO-GENERATED" banner, and the
generator fails closed on duplicate ids/names, unknown writers or bad schemas.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "config" / "refmem" / "read_catalog.yaml"
HEADER = ROOT / "components" / "distributed_refmem" / "inc" / "refmem_read_catalog.h"
TABLE_C = ROOT / "components" / "distributed_refmem" / "src" / "refmem_read_catalog_table.c"

WRITERS = {
    "SYNC_IO": 0,
    "TRIGGER": 1,
    "GUIDE": 2,
    "BOOT": 3,
    "TDMA": 4,
    "CAL": 5,
    "REFMEM": 6,
}

MAX_SCHEMA_WORDS = 8


def fail(message: str) -> int:
    print(message, file=sys.stderr)
    return 1


def main() -> int:
    data = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    keys = data.get("keys") or []
    if not keys:
        return fail("no read keys")
    seen_ids: set[int] = set()
    seen_names: set[str] = set()
    for row in keys:
        key_id = int(row["id"])
        if key_id <= 0 or key_id > 0xFF:
            return fail(f"bad key id {key_id}")
        if key_id in seen_ids:
            return fail(f"duplicate key id {key_id}")
        name = str(row["name"])
        if not name or name in seen_names:
            return fail(f"duplicate/empty key name {name!r}")
        if row["writer"] not in WRITERS:
            return fail(f"unknown writer {row['writer']}")
        schema = row.get("schema") or []
        if not 1 <= len(schema) <= MAX_SCHEMA_WORDS:
            return fail(f"bad schema length for {name}")
        if any(not str(word) for word in schema):
            return fail(f"empty schema word for {name}")
        seen_ids.add(key_id)
        seen_names.add(name)

    header = [
        "/* AUTO-GENERATED by tools/refmem/refmem_read_catalog_gen.py; do not edit. */",
        "#ifndef REFMEM_READ_CATALOG_H",
        "#define REFMEM_READ_CATALOG_H",
        "",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "#define REFMEM_READ_CATALOG_MAX_SCHEMA_WORDS %du" % MAX_SCHEMA_WORDS,
        "",
        "typedef enum {",
    ]
    for row in keys:
        header.append("    REFMEM_READ_KEY_%s = %du," % (str(row["name"]).upper(), int(row["id"])))
    header += [
        "} refmem_read_key_id_t;",
        "",
        "typedef struct {",
        "    uint8_t id;",
        "    const char *name;",
        "    uint8_t writer;",
        "    uint8_t schema_words;",
        "    const char *const *schema;",
        "} refmem_read_key_t;",
        "",
        "extern const refmem_read_key_t refmem_read_catalog[];",
        "extern const uint32_t refmem_read_catalog_count;",
        "",
        "const refmem_read_key_t *refmem_read_catalog_find(uint8_t id);",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif",
        "",
    ]

    table = ["/* AUTO-GENERATED by tools/refmem/refmem_read_catalog_gen.py; do not edit. */",
             '#include "refmem_read_catalog.h"', "", "#include <stddef.h>", ""]
    for row in keys:
        name = str(row["name"])
        schema = row["schema"]
        table.append("static const char *const k_schema_%s[%d] = {" % (name, len(schema)))
        for word in schema:
            table.append('    "%s",' % str(word))
        table.append("};")
        table.append("")
    table.append("const refmem_read_key_t refmem_read_catalog[] = {")
    for row in keys:
        name = str(row["name"])
        table.append(
            '    {%du, "%s", %du, %du, k_schema_%s},'
            % (int(row["id"]), name, WRITERS[row["writer"]], len(row["schema"]), name)
        )
    table.append("};")
    table += [
        "",
        "const uint32_t refmem_read_catalog_count =",
        "    (uint32_t)(sizeof(refmem_read_catalog) / sizeof(refmem_read_catalog[0]));",
        "",
        "const refmem_read_key_t *refmem_read_catalog_find(uint8_t id)",
        "{",
        "    for (uint32_t i = 0u; i < refmem_read_catalog_count; i++) {",
        "        if (refmem_read_catalog[i].id == id) {",
        "            return &refmem_read_catalog[i];",
        "        }",
        "    }",
        "    return NULL;",
        "}",
        "",
    ]

    header_text = "\n".join(header)
    table_text = "\n".join(table)

    if "--check" in sys.argv:
        drift = []
        for path, text in ((HEADER, header_text), (TABLE_C, table_text)):
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current.replace("\r\n", "\n") != text.replace("\r\n", "\n"):
                drift.append(str(path))
        if drift:
            print("generated files differ from config: " + ", ".join(drift),
                  file=sys.stderr)
            return 1
        print("read catalog is up to date (%d keys)" % len(keys))
        return 0

    HEADER.write_text(header_text, encoding="utf-8", newline="\n")
    TABLE_C.write_text(table_text, encoding="utf-8", newline="\n")
    print("wrote %s and %s (%d keys)" % (HEADER, TABLE_C, len(keys)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
