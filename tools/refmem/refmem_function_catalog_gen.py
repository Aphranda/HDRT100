#!/usr/bin/env python3
"""Generate the REFMEM application function catalog table from YAML."""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
FUNCTION_SOURCE = ROOT / "config" / "refmem" / "function_catalog.yaml"
COMMAND_SOURCE = ROOT / "config" / "refmem" / "command_catalog.yaml"
HEADER = ROOT / "components" / "distributed_refmem" / "inc" / "refmem_function_catalog.h"
TABLE_C = ROOT / "components" / "distributed_refmem" / "src" / "refmem_function_catalog.c"
CSV_OUT = ROOT / "out" / "refmem" / "SCPI_REFMEM_FUNCTION_CATALOG.csv"

FAILURE_POLICIES = {"abort_remaining": 0, "continue_report": 1}
MAX_STEPS = 8


def main() -> int:
    command_data = yaml.safe_load(COMMAND_SOURCE.read_text(encoding="utf-8"))
    command_words = {
        int(row["id"]): int(row.get("param_words", 0))
        for row in (command_data.get("commands") or [])
    }
    data = yaml.safe_load(FUNCTION_SOURCE.read_text(encoding="utf-8"))
    functions = data.get("functions") or []
    if not functions:
        print("no functions", file=sys.stderr)
        return 1

    seen_ids = set()
    seen_names = set()
    for row in functions:
        fid = int(row["id"])
        if fid <= 0 or fid > 0xFFFF:
            print(f"bad function id {fid}", file=sys.stderr)
            return 1
        if fid in seen_ids:
            print(f"duplicate function id {fid}", file=sys.stderr)
            return 1
        if row["name"] in seen_names:
            print(f"duplicate function name {row['name']}", file=sys.stderr)
            return 1
        if row["failure_policy"] not in FAILURE_POLICIES:
            print(f"unknown failure_policy {row['failure_policy']}", file=sys.stderr)
            return 1
        arg_words = int(row.get("arg_words", 0))
        if not 0 <= arg_words <= 16:
            print(f"arg_words out of range for {row['name']}", file=sys.stderr)
            return 1
        steps = row.get("steps") or []
        if not 1 <= len(steps) <= MAX_STEPS:
            print(f"step count out of range for {row['name']}", file=sys.stderr)
            return 1
        for step in steps:
            cid = int(step["command_id"])
            if cid not in command_words:
                print(f"unknown command_id {cid} in {row['name']}", file=sys.stderr)
                return 1
            base = int(step.get("arg_base", 0))
            words = int(step.get("arg_words", 0))
            if base < 0 or words < 0 or base + words > arg_words:
                print(f"arg slice out of range in {row['name']}", file=sys.stderr)
                return 1
            if words != command_words[cid]:
                print(
                    f"step {cid} words {words} != catalog {command_words[cid]} "
                    f"in {row['name']}",
                    file=sys.stderr,
                )
                return 1
        seen_ids.add(fid)
        seen_names.add(row["name"])

    lines = [
        "/* AUTO-GENERATED by tools/refmem/refmem_function_catalog_gen.py; do not edit. */",
        "#ifndef REFMEM_FUNCTION_CATALOG_H",
        "#define REFMEM_FUNCTION_CATALOG_H",
        "",
        "#include <stdbool.h>",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "#define REFMEM_FUNCTION_MAX_STEPS 8u",
        "#define REFMEM_FUNCTION_ARG_MAX 16u",
        "",
        "typedef enum {",
        "    REFMEM_FUNCTION_ABORT_REMAINING = 0u,",
        "    REFMEM_FUNCTION_CONTINUE_REPORT = 1u,",
        "} refmem_function_failure_policy_t;",
        "",
        "typedef struct {",
        "    uint16_t command_id;",
        "    uint8_t arg_base;",
        "    uint8_t arg_words;",
        "} refmem_function_step_t;",
        "",
        "typedef struct {",
        "    uint16_t id;",
        "    uint8_t failure_policy;",
        "    uint8_t arg_words;",
        "    uint8_t step_count;",
        "    uint8_t reserved;",
        "    const char *name;",
        "    refmem_function_step_t steps[REFMEM_FUNCTION_MAX_STEPS];",
        "} refmem_function_entry_t;",
        "",
        "enum {",
    ]
    for row in functions:
        lines.append(f"    REFMEM_FUNC_ID_{row['name']} = {int(row['id'])}u,")
    lines += [
        "};",
        "",
        "extern const refmem_function_entry_t refmem_function_catalog[];",
        "extern const uint32_t refmem_function_catalog_count;",
        "",
        "const refmem_function_entry_t *refmem_function_find_by_id(uint16_t id);",
        "const refmem_function_entry_t *refmem_function_find_by_name(const char *name);",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* REFMEM_FUNCTION_CATALOG_H */",
        "",
    ]
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    table_lines = [
        "/* AUTO-GENERATED by tools/refmem/refmem_function_catalog_gen.py; do not edit. */",
        '#include "refmem_function_catalog.h"',
        "",
        "#include <stddef.h>",
        "#include <string.h>",
        "",
        "const refmem_function_entry_t refmem_function_catalog[] = {",
    ]
    for row in functions:
        steps = row.get("steps") or []
        step_cells = []
        for i in range(MAX_STEPS):
            if i < len(steps):
                step = steps[i]
                step_cells.append(
                    f"{{{int(step['command_id'])}u, {int(step.get('arg_base', 0))}u, "
                    f"{int(step.get('arg_words', 0))}u}}"
                )
            else:
                step_cells.append("{0u, 0u, 0u}")
        table_lines.append(
            "    {"
            f"{int(row['id'])}u, {FAILURE_POLICIES[row['failure_policy']]}u, "
            f"{int(row.get('arg_words', 0))}u, {len(steps)}u, 0u, "
            f'"{row["name"]}", {{{", ".join(step_cells)}}}'
            "},"
        )
    table_lines += [
        "};",
        "",
        "const uint32_t refmem_function_catalog_count =",
        "    (uint32_t)(sizeof(refmem_function_catalog) /",
        "               sizeof(refmem_function_catalog[0]));",
        "",
        "const refmem_function_entry_t *refmem_function_find_by_id(uint16_t id)",
        "{",
        "    for (uint32_t i = 0u; i < refmem_function_catalog_count; ++i) {",
        "        if (refmem_function_catalog[i].id == id) {",
        "            return &refmem_function_catalog[i];",
        "        }",
        "    }",
        "    return NULL;",
        "}",
        "",
        "const refmem_function_entry_t *refmem_function_find_by_name(",
        "    const char *name)",
        "{",
        "    if (name == NULL) {",
        "        return NULL;",
        "    }",
        "    for (uint32_t i = 0u; i < refmem_function_catalog_count; ++i) {",
        "        if (strcmp(refmem_function_catalog[i].name, name) == 0) {",
        "            return &refmem_function_catalog[i];",
        "        }",
        "    }",
        "    return NULL;",
        "}",
        "",
    ]
    TABLE_C.write_text("\n".join(table_lines), encoding="utf-8", newline="\n")

    CSV_OUT.parent.mkdir(parents=True, exist_ok=True)
    with CSV_OUT.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["function_id", "name", "failure_policy", "arg_words",
                         "step_index", "command_id", "arg_base", "arg_words"])
        for row in functions:
            for i, step in enumerate(row.get("steps") or []):
                writer.writerow([
                    row["id"], row["name"], row["failure_policy"],
                    row.get("arg_words", 0), i, step["command_id"],
                    step.get("arg_base", 0), step.get("arg_words", 0),
                ])
    print(f"generated {HEADER} ({len(functions)} functions)")
    print(f"generated {TABLE_C}")
    print(f"generated {CSV_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
