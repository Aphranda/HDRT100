#!/usr/bin/env python3
"""Generate the REFMEM command catalog C table and CSV from YAML."""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "config" / "refmem" / "command_catalog.yaml"
HEADER = ROOT / "components" / "distributed_refmem" / "inc" / "refmem_command_catalog.h"
TABLE_C = ROOT / "components" / "distributed_refmem" / "src" / "refmem_command_catalog_table.c"
CSV_OUT = ROOT / "out" / "refmem" / "SCPI_REFMEM_CATALOG.csv"

COMMAND_TYPES = {
    "NONE": 0,
    "CONFIG_STAGE": 1,
    "CONFIG_ACTIVATE": 2,
    "START": 3,
    "STOP": 4,
    "ARM": 5,
    "FIRE_LOAD": 6,
    "CAL_START": 7,
    "CAL_SAVE_LOAD_ACTIVATE": 8,
    "SYNC_START_STOP": 9,
    "SYNC_RELOCK_HOLDOVER": 10,
    "FAULT_CLEAR": 11,
    "RESOURCE_JOB": 12,
    "MAINTENANCE": 13,
    "NODE_LOAD_STAGE": 14,
    "BOARD_CAPABILITY_STAGE": 15,
    "TABLE_PACKAGE_STAGE": 16,
    "TABLE_PACKAGE_ACTIVATE": 17,
    "LEASE_TAKE": 18,
    "LEASE_RELEASE": 19,
    "TDMA_RING_TOPOLOGY": 20,
    "TDMA_SEAT_ROTATION": 21,
    "TDMA_PERIOD": 22,
    "TDMA_LOAD_MASK": 23,
    "DPLL_ROLE": 24,
    "DPLL_TUNE": 25,
    "DPLL_OVERRIDE": 26,
    "VDC_REFERENCE_CONFIG": 27,
    "VDC_OUTPUT_DELAY": 28,
    "VDC_OUTPUT_TIMING": 29,
    "T2_CONFIGURE": 30,
    "T2_MOUNT": 31,
    "T2_UNMOUNT": 32,
    "VDC_STOP": 33,
    "VDC_START": 34,
}

OWNERS = {
    "REFMEM": 0,
    "TDMA": 1,
    "T2": 2,
    "CAL": 3,
    "VDC": 4,
    "TRIGGER": 5,
    "STORAGE": 6,
    "SYSTEM": 7,
}

PARAM_KINDS = {"inline": 0, "ref": 1}


def main() -> int:
    data = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    commands = data.get("commands") or []
    if not commands:
        print("no commands", file=sys.stderr)
        return 1
    seen_ids = set()
    seen_names = set()
    for row in commands:
        cid = int(row["id"])
        if cid <= 0 or cid > 0xFFFF:
            print(f"bad id {cid}", file=sys.stderr)
            return 1
        if cid in seen_ids:
            print(f"duplicate id {cid}", file=sys.stderr)
            return 1
        if row["name"] in seen_names:
            print(f"duplicate name {row['name']}", file=sys.stderr)
            return 1
        if row["command_type"] not in COMMAND_TYPES:
            print(f"unknown command_type {row['command_type']}", file=sys.stderr)
            return 1
        if row["owner"] not in OWNERS:
            print(f"unknown owner {row['owner']}", file=sys.stderr)
            return 1
        if row["param_kind"] not in PARAM_KINDS:
            print(f"unknown param_kind {row['param_kind']}", file=sys.stderr)
            return 1
        if not 0 <= int(row.get("param_words", 0)) <= 16:
            print(f"param_words out of range for {row['name']}", file=sys.stderr)
            return 1
        seen_ids.add(cid)
        seen_names.add(row["name"])

    lines = [
        "/* AUTO-GENERATED by tools/refmem/refmem_command_catalog_gen.py; do not edit. */",
        "#ifndef REFMEM_COMMAND_CATALOG_H",
        "#define REFMEM_COMMAND_CATALOG_H",
        "",
        "#include <stdbool.h>",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "#define REFMEM_CATALOG_PARAM_INLINE 0u",
        "#define REFMEM_CATALOG_PARAM_REF 1u",
        "",
        "typedef struct {",
        "    uint16_t id;",
        "    uint8_t command_type;",
        "    uint8_t owner;",
        "    uint8_t realtime;",
        "    uint8_t param_words;",
        "    uint8_t param_kind;",
        "    uint8_t idempotent;",
        "    uint16_t allowed_states;",
        "    uint32_t required_capabilities;",
        "    uint32_t timeout_us;",
        "    const char *name;",
        "    const char *scpi;",
        "} refmem_catalog_entry_t;",
        "",
        "enum {",
    ]
    for row in commands:
        lines.append(f"    REFMEM_CMD_ID_{row['name']} = {int(row['id'])}u,")
    lines += [
        "};",
        "",
        "extern const refmem_catalog_entry_t refmem_command_catalog[];",
        "extern const uint32_t refmem_command_catalog_count;",
        "",
        "const refmem_catalog_entry_t *refmem_command_catalog_find_by_id(uint16_t id);",
        "const refmem_catalog_entry_t *refmem_command_catalog_find_by_name(const char *name);",
        "bool refmem_command_catalog_validate_params(const refmem_catalog_entry_t *entry,",
        "                                            uint32_t param_words,",
        "                                            uint32_t param_kind);",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* REFMEM_COMMAND_CATALOG_H */",
        "",
    ]
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    table_lines = [
        "/* AUTO-GENERATED by tools/refmem/refmem_command_catalog_gen.py; do not edit. */",
        '#include "refmem_command_catalog.h"',
        "",
        "const refmem_catalog_entry_t refmem_command_catalog[] = {",
    ]
    for row in commands:
        state_list = [int(s) for s in (row.get("allowed_states") or [0])]
        states = 0 if state_list == [0] else sum(1 << s for s in state_list)
        table_lines.append(
            "    {"
            f"{int(row['id'])}u, {COMMAND_TYPES[row['command_type']]}u, "
            f"{OWNERS[row['owner']]}u, {int(bool(row.get('realtime', False)))}u, "
            f"{int(row.get('param_words', 0))}u, {PARAM_KINDS[row['param_kind']]}u, "
            f"{int(bool(row.get('idempotent', False)))}u, {states}u, "
            f"{int(row.get('required_capabilities', 0))}u, "
            f"{int(row.get('timeout_us', 0))}u, "
            f'"{row["name"]}", "{row["scpi"]}"'
            "},"
        )
    table_lines += [
        "};",
        "",
        "const uint32_t refmem_command_catalog_count =",
        "    (uint32_t)(sizeof(refmem_command_catalog) / sizeof(refmem_command_catalog[0]));",
        "",
    ]
    TABLE_C.write_text("\n".join(table_lines), encoding="utf-8", newline="\n")

    CSV_OUT.parent.mkdir(parents=True, exist_ok=True)
    with CSV_OUT.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow([
            "id", "name", "scpi", "command_type", "owner", "realtime",
            "param_words", "param_kind", "params", "allowed_states",
            "required_capabilities", "idempotent", "timeout_us",
        ])
        for row in commands:
            writer.writerow([
                row["id"], row["name"], row["scpi"], row["command_type"],
                row["owner"], int(bool(row.get("realtime", False))),
                row.get("param_words", 0), row["param_kind"],
                " ".join(row.get("params") or []),
                ",".join(str(s) for s in row.get("allowed_states") or [0]),
                row.get("required_capabilities", 0),
                int(bool(row.get("idempotent", False))),
                row.get("timeout_us", 0),
            ])
    print(f"generated {HEADER} ({len(commands)} commands)")
    print(f"generated {CSV_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
