"""Source-scope classification and Git-index fingerprints for acceptance.

Extracted from the monolithic step library so the workflow and its dependency
modules can share the exact fingerprint definition.  The algorithm is
unchanged: an index blob per acceptance source plus the hashed content of every
modified/untracked acceptance source.
"""
from __future__ import annotations

import hashlib
import subprocess
from pathlib import Path
from typing import Iterable

try:  # package import (tests, workflow)
    from .acceptance_errors import AcceptanceError
except ImportError:  # top-level import (tools/hardware_acceptance on sys.path)
    from acceptance_errors import AcceptanceError

ROOT = Path(__file__).resolve().parents[2]
SOURCE_ROOTS = {
    "application", "boards", "bootloader", "cmake",
    "components", "config", "drivers", "linker", "middleware", "osal",
    "platform",
    "third_party",
}
SOURCE_ROOT_FILES = {
    "CMakeLists.txt", "CMakePresets.json", "pico_sdk_import.cmake",
}
SOURCE_EXCLUDES = {
    "config/hardware_acceptance/p3_acceptance_receipt.json",
    # A T2 acceptance receipt must not change the fingerprint it certifies (same rule as P3).
    "config/hardware_acceptance/t2_acceptance_receipt.json",
    # The host credential lives beside the P3 receipt and is regenerated by the
    # host gate; it must never perturb the firmware fingerprint (and vice versa).
    "config/hardware_acceptance/host_acceptance_receipt.json",
}


def _run_git(root: Path, *args: str, input_bytes: bytes | None = None) -> bytes:
    result = subprocess.run(
        ["git", *args], cwd=root, input=input_bytes, stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, check=False)
    if result.returncode != 0:
        raise AcceptanceError(
            f"git {' '.join(args)} failed: "
            f"{result.stderr.decode('utf-8', errors='replace').strip()}")
    return result.stdout


def is_acceptance_source(path: str) -> bool:
    normalized = path.replace("\\", "/")
    while normalized.startswith("./"):
        normalized = normalized[2:]
    if normalized in SOURCE_EXCLUDES:
        return False
    # The hardware credential certifies FIRMWARE only (2026-11-02 user
    # directive): docs, Python tooling, host tests and hook wiring have their own
    # gates, so changing them must neither invalidate nor demand a bench run.
    if normalized == "tests" or normalized.startswith("tests/"):
        return False
    if normalized == ".githooks" or normalized.startswith(".githooks/"):
        return False
    if normalized == "tools" or normalized.startswith("tools/"):
        return False
    if normalized == "docs" or normalized.startswith("docs/"):
        return False
    if normalized.endswith(".py") or normalized.endswith(".md"):
        return False
    item = Path(normalized)
    if normalized in SOURCE_ROOT_FILES:
        return True
    if not item.parts or item.parts[0] not in SOURCE_ROOTS:
        return False
    return True


def _tree_digest(rows: Iterable[tuple[str, str, str]]) -> tuple[str, int]:
    digest = hashlib.sha256()
    count = 0
    for path, mode, blob_id in sorted(rows, key=lambda row: row[0]):
        digest.update(path.encode("utf-8"))
        digest.update(b"\0")
        digest.update(mode.encode("ascii"))
        digest.update(b"\0")
        digest.update(blob_id.encode("ascii"))
        digest.update(b"\n")
        count += 1
    return digest.hexdigest(), count


def working_source_fingerprint(root: Path = ROOT) -> tuple[str, int]:
    entries = {
        path: (mode, oid) for path, mode, oid in _index_entries(root)
    }
    raw = _run_git(
        root, "ls-files", "--modified", "--deleted", "--others",
        "--exclude-standard", "-z")
    changed = sorted({
        item.decode("utf-8", errors="surrogateescape")
        for item in raw.split(b"\0") if item
    })
    for path in changed:
        normalized = path.replace("\\", "/")
        if not is_acceptance_source(normalized):
            continue
        full = root / path
        if not full.is_file():
            entries.pop(normalized, None)
            continue
        blob_id = _run_git(
            root, "hash-object", f"--path={normalized}", normalized
        ).decode("ascii").strip()
        mode = entries.get(normalized, ("100644", ""))[0]
        entries[normalized] = (mode, blob_id)
    return _tree_digest(
        (path, mode, oid) for path, (mode, oid) in entries.items())


def _index_entries(root: Path) -> list[tuple[str, str, str]]:
    raw = _run_git(root, "ls-files", "--stage", "-z")
    entries = []
    for entry in raw.split(b"\0"):
        if not entry or b"\t" not in entry:
            continue
        metadata, raw_path = entry.split(b"\t", 1)
        fields = metadata.split()
        if len(fields) != 3 or fields[2] != b"0":
            continue
        path = raw_path.decode("utf-8", errors="surrogateescape")
        if is_acceptance_source(path):
            entries.append((path.replace("\\", "/"),
                            fields[0].decode("ascii"),
                            fields[1].decode("ascii")))
    return sorted(entries)


def staged_source_fingerprint(root: Path = ROOT) -> tuple[str, int]:
    entries = _index_entries(root)
    return _tree_digest(entries)


def changed_staged_sources(root: Path = ROOT) -> list[str]:
    raw = _run_git(root, "diff", "--cached", "--name-only", "-z")
    return sorted(
        path for path in (
            item.decode("utf-8", errors="surrogateescape")
            for item in raw.split(b"\0") if item)
        if is_acceptance_source(path))


def unstaged_sources(root: Path = ROOT) -> list[str]:
    raw = _run_git(root, "diff", "--name-only", "-z")
    return sorted(
        path for path in (
            item.decode("utf-8", errors="surrogateescape")
            for item in raw.split(b"\0") if item)
        if is_acceptance_source(path))


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()
